    private void Delete_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Delete_btnActionPerformed
        // Get the selected row index
    int del_row = category_table.getSelectedRow();

    // Check if a row is selected
    if (del_row == -1) {
        // Show message if no row is selected
        JOptionPane.showMessageDialog(null, "Select The Delete Category");
    } else {
            // Get the category name from the selected row
            String del_category = (String) category_table.getValueAt(del_row, 1);

            // Show confirmation dialog
            int r = JOptionPane.showConfirmDialog(null, "Do you really wanna delete?", 
                                                  "Deletion Confirmation", JOptionPane.YES_NO_OPTION);
            if (r == JOptionPane.YES_OPTION) {
                        // If "Yes" is selected, delete the category
                        try {
                            String query = "DELETE FROM category WHERE category_list='" + del_category + "'";
                            connection.s.executeUpdate(query);
                            JOptionPane.showMessageDialog(null, "Category Deleted Successfully");

                            // Refresh the category list
                            getCategory();
                        } catch (Exception e) {
                            JOptionPane.showMessageDialog(null, e);
                        }
            }
    }
    }//GEN-LAST:event_Delete_btnActionPerformed


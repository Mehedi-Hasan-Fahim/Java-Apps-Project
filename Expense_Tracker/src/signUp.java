    private boolean isValidEmail(String email) {
    // Define the email pattern
    String emailRegex = "^[a-zA-Z0-9_+&*-]+(?:\\.[a-zA-Z0-9_+&*-]+)*@(?:[a-zA-Z0-9-]+\\.)+[a-zA-Z]{2,7}$";
    
    // Compile the regex
    Pattern pattern = Pattern.compile(emailRegex);
    
    // Match the email to the pattern
    Matcher matcher = pattern.matcher(email);
    
    // If regex matches, perform domain validation
    if (matcher.matches()) {
        String[] parts = email.split("@");
        String domain = parts[1].toLowerCase(); // Extract the domain part and convert to lowercase

        // Check against a list of valid domains
        String[] validDomains = {"gmail.com", "yahoo.com", "outlook.com", "hotmail.com"};
        for (String validDomain : validDomains) {
            if (domain.equals(validDomain)) {
                return true; // Valid email
            }
        }
        return false; // Invalid domain
    }

    return false; // Regex doesn't match
}

    
    

     void showExpenses(){
        try{
            ResultSet rs = null;
            DefaultTableModel dtm= (DefaultTableModel)expense_table.getModel();
             dtm.setRowCount(0);
             LocalDate cdate = LocalDate.now();
             LocalDate bdate = cdate.minusDays(20);
             
             String query = "select* from expenses where ( Date_Issue<= '"+cdate+"' or Date_Issue >='"+bdate+"' ) and ( email = '"+email+"' and password_ = '"+password+"' ) ";
             rs = connection.s.executeQuery(query);
             int total_expense_amount=0;
             while(rs.next()){
                    int exp_det1 = rs.getInt("ID");
                    String exp_det2 = rs.getString("Date_Issue");
                    String exp_det3 = rs.getString("Category");
                    String exp_det4 = rs.getString("Remarks");
                    int exp_det5 = rs.getInt("Amount");
                    total_expense_amount+=exp_det5;
                    Vector row = new Vector();
                    row.add(exp_det1);
                    row.add(exp_det2);
                    row.add(exp_det3);
                    row.add(exp_det4);
                    row.add(exp_det5);
                    dtm.addRow(row);
                   
             }
              total_expense.setText(total_expense_amount+"");
              System.out.println(total_expense_amount);
    
        }catch(Exception e){
            JOptionPane.showMessageDialog(null,e);
    }
    }
    
    


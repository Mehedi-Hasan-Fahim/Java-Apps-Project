    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
    // Get the selected row index
    int del_row = expense_table.getSelectedRow();
    System.out.println(del_row);
    // Check if a row is selected
    if (del_row == -1) {
        // Show message if no row is selected
        JOptionPane.showMessageDialog(null, "Select The Delete Expense");
    } else {
            // Get the category name from the selected row
            int del_expense_id = (int) expense_table.getValueAt(del_row, 0);
            System.out.println(del_expense_id);

            // Show confirmation dialog
            int r = JOptionPane.showConfirmDialog(null, "Do you really wanna delete?", 
                                                  "Deletion Confirmation", JOptionPane.YES_NO_OPTION);
            if (r == JOptionPane.YES_OPTION) {
                        // If "Yes" is selected, delete the category
                        try {
                            String query = "DELETE FROM expenses WHERE ID ='" + del_expense_id + "'";
                            connection.s.executeUpdate(query);
                            JOptionPane.showMessageDialog(null, "Expense Deleted Successfully");
                            // Refresh the expenses
                            showExpenses();
                        } catch (Exception e) {
                            JOptionPane.showMessageDialog(null, e);
                        }
            }
        }     
    }//GEN-LAST:event_DeleteActionPerformed



public void downloadExpenses() {
    try {
        // Create an Excel workbook and sheet
        Workbook workbook = new XSSFWorkbook();
        Sheet sheet = workbook.createSheet("Expenses");

        // Get the table model
        DefaultTableModel dtm = (DefaultTableModel) expense_table.getModel();

        // Write header row
        Row headerRow = sheet.createRow(0);
        for (int col = 0; col < dtm.getColumnCount(); col++) {
            Cell cell = headerRow.createCell(col);
            cell.setCellValue(dtm.getColumnName(col));
        }

        // Write data rows
        for (int row = 0; row < dtm.getRowCount(); row++) {
            Row dataRow = sheet.createRow(row + 1);
            for (int col = 0; col < dtm.getColumnCount(); col++) {
                Cell cell = dataRow.createCell(col);
                Object value = dtm.getValueAt(row, col);
                if (value != null) {
                    cell.setCellValue(value.toString());
                }
            }
        }

        // Use JFileChooser to choose file name and location
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Save Excel File");
        fileChooser.setSelectedFile(new File("expenses.xlsx")); // Default file name
        fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Excel Files", "xlsx"));

        int userSelection = fileChooser.showSaveDialog(null);
        if (userSelection == JFileChooser.APPROVE_OPTION) {
            File fileToSave = fileChooser.getSelectedFile();

            // Append ".xlsx" if not provided
            if (!fileToSave.getName().endsWith(".xlsx")) {
                fileToSave = new File(fileToSave.getAbsolutePath() + ".xlsx");
            }

            // Write the workbook to the selected file
            try (FileOutputStream fileOut = new FileOutputStream(fileToSave)) {
                workbook.write(fileOut);
                JOptionPane.showMessageDialog(null, "Data exported successfully to " + fileToSave.getAbsolutePath());
            }
        } else {
            JOptionPane.showMessageDialog(null, "Export cancelled by user.");
        }

        // Close the workbook
        workbook.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error exporting data: " + e.getMessage());
    }
}



public void uploadExpenses() {
    try {
        // Open a file chooser to select the Excel file
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Select Excel File to Upload");
        fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Excel Files", "xls", "xlsx"));

        int userSelection = fileChooser.showOpenDialog(null);
        if (userSelection != JFileChooser.APPROVE_OPTION) {
            JOptionPane.showMessageDialog(null, "No file selected. Upload cancelled.");
            return;
        }

        File selectedFile = fileChooser.getSelectedFile();

        // Read the Excel file
        FileInputStream fis = new FileInputStream(selectedFile);
        Workbook workbook = new XSSFWorkbook(fis);
        Sheet sheet = workbook.getSheetAt(0); // Assuming the first sheet contains the data

        DataFormatter dataFormatter = new DataFormatter(); // To read cell data in various formats
        SimpleDateFormat preferredDateFormat = new SimpleDateFormat("yyyy-MM-dd");

        // Iterate over the rows in the sheet, skipping the header row
        int rowCount = 0;
        for (Row row : sheet) {
            if (rowCount == 0) { // Skip the header row
                rowCount++;
                continue;
            }

            // Extract values from each column
            Cell dateIssueCell = row.getCell(1);
            Cell categoryCell = row.getCell(2);
            Cell remarksCell = row.getCell(3);
            Cell amountCell = row.getCell(4);

            // Validate data (ensure no null values)
            if (dateIssueCell == null || categoryCell == null || remarksCell == null || amountCell == null) {
                continue; // Skip invalid rows
            }

            String email = this.email;
            String password = this.password;

            // Handle Date_Issue cell with flexibility
            String dateString = "";
            if (dateIssueCell.getCellType() == CellType.NUMERIC && DateUtil.isCellDateFormatted(dateIssueCell)) {
                // If the cell contains a date
                Date date = dateIssueCell.getDateCellValue();
                dateString = preferredDateFormat.format(date);
            } else {
                // Use DataFormatter to handle textual or improperly formatted date strings
                String rawDate = dataFormatter.formatCellValue(dateIssueCell);
                try {
                    // Try to parse and format the date
                    Date date = new SimpleDateFormat("yyyy-MM-dd").parse(rawDate);
                    dateString = preferredDateFormat.format(date);
                } catch (Exception e) {
                    // If parsing fails, skip this row
                    JOptionPane.showMessageDialog(null, "Invalid date format in row " + (row.getRowNum() + 1) + ". Skipping.");
                    continue;
                }
            }

            // Handle Category, Remarks, and Amount cells
            String category = categoryCell.getStringCellValue();
            String remarks = remarksCell.getStringCellValue();

            // Handle Amount cell (numeric or string)
            int amount = 0;
            if (amountCell.getCellType() == CellType.NUMERIC) {
                amount = (int) amountCell.getNumericCellValue();
            } else if (amountCell.getCellType() == CellType.STRING) {
                try {
                    amount = Integer.parseInt(amountCell.getStringCellValue());
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(null, "Invalid amount format in row " + (row.getRowNum() + 1) + ". Skipping.");
                    continue; // Skip the row if the amount is not a valid number
                }
            }

            // Insert into database
            String query = "INSERT INTO expenses (email, password_, Date_Issue, Category, Remarks, Amount) " +
                           "VALUES ('" + email + "','" + password + "','" + dateString + "','" + category + "','" + remarks + "'," + amount + ")";
            connection.s.executeUpdate(query);
        }

        // Close resources
        workbook.close();
        fis.close();

        // Notify success
        JOptionPane.showMessageDialog(null, "Expenses uploaded successfully!");

        // Refresh the table
        showExpenses();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error uploading expenses: " + e.getMessage());
    }
}



    
    
